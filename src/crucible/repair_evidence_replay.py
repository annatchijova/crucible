"""Offline reconstruction of a captured L7 repair decision.

Replay consumes only the sealed bundle's recorded provider projections. It
never constructs a network executor or contacts a provider.
"""

from __future__ import annotations

from copy import deepcopy
from typing import Any

from . import behavioral
from .bob import (
    LLMProposer,
    REPAIR_PROPOSAL_MAX_TOKENS,
    REPAIR_SYSTEM_PROMPT,
    normalize_skill_frontmatter_prefix,
)
from .capture_bundle import oracle_identity
from .capture_contract import ADAPTER_VERSION
from .ir import canonical_bytes, digest_payload
from .repair_evidence import (
    EVIDENCE_VERSION,
    MAX_EVIDENCE_BYTES,
    _usable,
    verify_repair_evidence,
)
from .repair_loop import LOOP_VERSION, run_repair_loop

REPLAY_VERSION = "crucible-repair-evidence-replay/v1"
PROVIDER = "nebius-token-factory"


class _NotReplayable(ValueError):
    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


class _RecordedProposer(LLMProposer):
    """Supply the captured proposal response to the existing repair loop."""

    def __init__(self, event: dict[str, Any] | None):
        super().__init__(api_key="offline-replay")
        self.event = event
        self.error_reason: str | None = None
        self.used = False

    def propose(self, finding, skill_text, context):
        if self.used or self.event is None:
            self.error_reason = "missing-or-duplicate-proposal-event"
            return {"proposed_text": None, "blocked": False,
                    "rationale": "proposal event unavailable during offline replay",
                    "proposer": "llm-nebius"}
        self.used = True
        system = REPAIR_SYSTEM_PROMPT
        user = self._build_prompt(finding, skill_text, context)
        try:
            _check_request(
                self.event,
                stage="repair_proposal",
                model=self.NEBIUS_MODEL,
                temperature=0,
                max_tokens=REPAIR_PROPOSAL_MAX_TOKENS,
                system_prompt=system,
                user_prompt=user,
            )
        except _NotReplayable as exc:
            self.error_reason = exc.reason
            return {"proposed_text": None, "blocked": False,
                    "rationale": "captured proposal request differs from this implementation",
                    "proposer": "llm-nebius"}
        response = self.event["response_projection"]
        metadata = {
            "model": self.NEBIUS_MODEL,
            "proposer": "llm-nebius",
            "response_id": response.get("response_id"),
            "finish_reason": response.get("finish_reason"),
            "usage": response.get("usage"),
            "truncated": response.get("truncated"),
        }
        if not _usable(response):
            return {
                **metadata,
                "proposed_text": None,
                "blocked": self.event["capture"]["status"] == "BLOCKED",
                "error": response.get("error") or "incomplete-provider-response",
                "rationale": "provider response retained but not eligible for repair",
            }
        proposed_text, removed_leading_line_breaks = normalize_skill_frontmatter_prefix(
            response["output"]
        )
        rationale = "generated by Nemotron via Nebius Token Factory"
        if removed_leading_line_breaks:
            rationale += "; removed leading line breaks before frontmatter"
        return {
            **metadata,
            "proposed_text": proposed_text if proposed_text.strip() else None,
            "blocked": False,
            "rationale": rationale,
        }


class _RecordedExecutor:
    """Supply captured behavioral outputs and enforce their original inputs."""

    model = behavioral.NEBIUS_DEFAULT_MODEL
    provider = PROVIDER
    temperature = behavioral.NEBIUS_DEFAULT_TEMPERATURE
    max_tokens = behavioral.NEBIUS_DEFAULT_MAX_TOKENS

    def __init__(self, events: list[dict[str, Any]]):
        self.events = list(events)
        self.error_reason: str | None = None

    def execute(self, system_prompt: str, user_prompt: str) -> dict[str, Any]:
        if not self.events:
            self.error_reason = "missing-behavioral-event"
            raise _NotReplayable(self.error_reason)
        event = self.events.pop(0)
        _check_request(
            event,
            stage="behavioral_observation",
            model=self.model,
            temperature=self.temperature,
            max_tokens=self.max_tokens,
            system_prompt=system_prompt,
            user_prompt=user_prompt,
        )
        response = event["response_projection"]
        if not _usable(response):
            return {
                "output": "",
                "error": response.get("error") or "incomplete-provider-response",
                "model": self.model,
                "provider": self.provider,
                "temperature": self.temperature,
                "max_tokens": self.max_tokens,
                "usage": response.get("usage"),
                "response_id": response.get("response_id"),
                "finish_reason": response.get("finish_reason"),
                "truncated": response.get("truncated"),
            }
        return {
            "output": response["output"],
            "error": None,
            "model": self.model,
            "provider": self.provider,
            "temperature": self.temperature,
            "max_tokens": self.max_tokens,
            "usage": response.get("usage"),
            "response_id": response.get("response_id"),
            "finish_reason": response.get("finish_reason"),
            "truncated": False,
            "runtime_metadata_complete": True,
        }


def _check_request(
    event: dict[str, Any], *, stage: str, model: str, temperature: int,
    max_tokens: int, system_prompt: str, user_prompt: str,
) -> None:
    if event.get("stage") != stage:
        raise _NotReplayable("event-stage-mismatch")
    expected = {
        "provider": PROVIDER,
        "model": model,
        "temperature": temperature,
        "max_tokens": max_tokens,
        "system_prompt": system_prompt,
        "user_prompt": user_prompt,
    }
    if event.get("request_projection") != expected:
        raise _NotReplayable("captured-request-does-not-match-replay-input")


def _decision_view(report: dict[str, Any]) -> dict[str, Any]:
    """Exclude only executor implementation labels, which differ by design."""
    view = deepcopy(report)
    view.pop("loop_digest", None)
    executor = view.get("executor")
    if isinstance(executor, dict):
        executor.pop("type", None)
    behavioral_replay = view.get("behavioral_replay")
    if isinstance(behavioral_replay, dict):
        replay_executor = behavioral_replay.get("executor")
        if isinstance(replay_executor, dict):
            replay_executor.pop("type", None)
    return view


def replay_repair_evidence(bundle: dict[str, Any]) -> dict[str, Any]:
    """Recompute the deterministic L7 decision from recorded provider outputs.

    ``MATCH`` means the local implementation at the pinned loop/oracle
    identity reproduces the recorded decision surface. It does not authenticate
    the provider or prove that a remote model generated the retained bytes.
    """
    try:
        if len(canonical_bytes(bundle)) > MAX_EVIDENCE_BYTES:
            raise ValueError("bundle byte limit exceeded")
        valid = verify_repair_evidence(bundle)
    except (AttributeError, KeyError, RecursionError, TypeError, ValueError):
        valid = False
    if not valid:
        return {"schema_version": REPLAY_VERSION, "status": "INVALID_EVIDENCE",
                "reason": "bundle-integrity-or-shape-failed"}

    report = bundle.get("report")
    source = bundle.get("source")
    if type(report) is not dict or type(source) is not dict:
        return {"schema_version": REPLAY_VERSION, "status": "INVALID_EVIDENCE",
                "reason": "missing-report-or-source"}
    if source.get("base_audit_digest") != report.get("base_audit_digest"):
        return {"schema_version": REPLAY_VERSION, "status": "INVALID_EVIDENCE",
                "reason": "source-audit-digest-mismatch"}
    if (bundle.get("schema_version") != EVIDENCE_VERSION
            or bundle.get("request_adapter") != ADAPTER_VERSION
            or bundle.get("provider") != PROVIDER):
        return {"schema_version": REPLAY_VERSION, "status": "NOT_REPLAYABLE",
                "reason": "unsupported-evidence-contract"}
    if (bundle.get("loop_version") != LOOP_VERSION
            or report.get("loop_version") != LOOP_VERSION
            or bundle.get("loop_version") != report.get("loop_version")):
        return {"schema_version": REPLAY_VERSION, "status": "NOT_REPLAYABLE",
                "reason": "repair-loop-version-mismatch"}
    if bundle.get("oracle") != oracle_identity():
        return {"schema_version": REPLAY_VERSION, "status": "NOT_REPLAYABLE",
                "reason": "oracle-identity-mismatch"}

    corpus, task = source.get("corpus"), source.get("task")
    finding_index = source.get("finding_index")
    events = bundle.get("events")
    if (type(corpus) is not dict or any(type(k) is not str or type(v) is not str
                                        for k, v in corpus.items())
            or type(task) is not dict or type(finding_index) is not int
            or finding_index < 0 or type(events) is not list):
        return {"schema_version": REPLAY_VERSION, "status": "INVALID_EVIDENCE",
                "reason": "invalid-replay-inputs"}

    stages = [event.get("stage") for event in events]
    if stages not in ([], ["repair_proposal"],
                      ["repair_proposal", "behavioral_observation",
                       "behavioral_observation"]):
        return {"schema_version": REPLAY_VERSION, "status": "NOT_REPLAYABLE",
                "reason": "unexpected-event-sequence"}
    proposal_events = [e for e in events if e.get("stage") == "repair_proposal"]
    behavioral_events = [e for e in events if e.get("stage") == "behavioral_observation"]

    proposer = _RecordedProposer(proposal_events[0] if proposal_events else None)
    executor = _RecordedExecutor(behavioral_events)
    try:
        replayed = run_repair_loop(
            corpus=corpus,
            task=task,
            finding_index=finding_index,
            proposer=proposer,
            executor=executor,
        )
    except _NotReplayable as exc:
        return {"schema_version": REPLAY_VERSION, "status": "NOT_REPLAYABLE",
                "reason": exc.reason}
    except (KeyError, TypeError, ValueError):
        return {"schema_version": REPLAY_VERSION, "status": "INVALID_EVIDENCE",
                "reason": "replay-input-rejected"}

    if proposer.error_reason:
        return {"schema_version": REPLAY_VERSION, "status": "NOT_REPLAYABLE",
                "reason": proposer.error_reason}
    if proposal_events and not proposer.used:
        return {"schema_version": REPLAY_VERSION, "status": "NOT_REPLAYABLE",
                "reason": "unused-proposal-event"}
    if executor.error_reason or executor.events:
        return {"schema_version": REPLAY_VERSION, "status": "NOT_REPLAYABLE",
                "reason": executor.error_reason or "unused-behavioral-events"}

    recorded_view = _decision_view(report)
    replayed_view = _decision_view(replayed)
    recorded_digest = digest_payload(recorded_view)
    replayed_digest = digest_payload(replayed_view)
    matches = recorded_view == replayed_view
    return {
        "schema_version": REPLAY_VERSION,
        "status": "MATCH" if matches else "DIVERGED",
        "reason": None if matches else "recomputed-decision-differs",
        "recorded_outcome": report.get("outcome"),
        "replayed_outcome": replayed.get("outcome"),
        "recorded_loop_digest": report.get("loop_digest"),
        "replayed_loop_digest": replayed.get("loop_digest"),
        "recorded_decision_digest": recorded_digest,
        "replayed_decision_digest": replayed_digest,
        "decision_digest": replayed_digest,
        "comparison_scope": "decision-surface excluding executor class labels",
    }
